#!/usr/bin/env python3
"""Generate extension/src/shared.js from shared/prompt.json (single source of truth).

Usage:  python scripts/sync_shared.py          # writes the file
        python scripts/sync_shared.py --check  # exits 1 if out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "shared" / "prompt.json"
DST = ROOT / "extension" / "src" / "shared.js"

HEADER = "// GENERATED by scripts/sync_shared.py from shared/prompt.json - do not edit by hand.\n"


def render() -> str:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    body = json.dumps(data, indent=2, ensure_ascii=False)
    return (
        HEADER
        + f"globalThis.WA_SHARED = {body};\n"
        + "if (typeof module !== \"undefined\") module.exports = globalThis.WA_SHARED;\n"
    )


def main() -> int:
    out = render()
    if "--check" in sys.argv:
        current = DST.read_text(encoding="utf-8") if DST.exists() else ""
        if current != out:
            print("extension/src/shared.js is out of date; run scripts/sync_shared.py", file=sys.stderr)
            return 1
        return 0
    DST.write_text(out, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
